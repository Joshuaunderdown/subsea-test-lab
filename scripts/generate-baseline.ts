/**
 * Regenerates src/lib/baseline.ts – the golden values for the regression test.
 *
 * Always runs against BASELINE_BUILD (the verified release), never the
 * defective one. Only rerun this when a behaviour change has been reviewed
 * and intentionally accepted; otherwise regression tests lose their meaning.
 *
 *   npm run baseline:generate
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { BASELINE_BUILD } from "../src/lib/build";
import { runScenario } from "../src/lib/scenario";
import { DEFAULT_SEED } from "../src/lib/simulation";

const records = runScenario(BASELINE_BUILD);
const out = resolve(__dirname, "../src/lib/baseline.ts");

const body = `// AUTO-GENERATED by scripts/generate-baseline.ts – do not edit by hand.
// Golden outputs of the regression scenario from the verified build.
import type { ScenarioRecord } from "./scenario";

export const BASELINE_META = {
  buildVersion: ${JSON.stringify(BASELINE_BUILD.version)},
  seed: ${DEFAULT_SEED},
  steps: ${records.length},
} as const;

export const BASELINE_RECORDS: ScenarioRecord[] = [
${records.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
];
`;

writeFileSync(out, body);
console.log(`Wrote ${records.length} golden records (build ${BASELINE_BUILD.version}, seed ${DEFAULT_SEED}) to ${out}`);
